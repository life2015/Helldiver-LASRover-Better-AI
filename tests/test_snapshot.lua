local api={read=function(a,n)
    for _,b in ipairs(blocks)do
        local start=tonumber(ffi.cast('uintptr_t',b[1]))
        if a>=start and a+n<=start+b[2] then return ffi.string(ffi.cast('void *',a),n)end
    end
end,pointer=function(bytes)
    local p=ffi.new('uint64_t[1]');ffi.copy(p,bytes,8);local n=tonumber(p[0]);return n~=0 and n or nil
end}
local passed=0
local function test(name,fn)fn();passed=passed+1;print('PASS '..name)end
test('complete local laser ownership chain and candidate decoding',function()
    local s=S.read(api,game);assert(s.id==103 and s.target==201 and s.synced and #s.candidates==2)
    assert(s.candidates[1].eligible and s.candidates[2].eligible and s.candidates[1].valid())
end)
test('gas backpack is rejected',function()
    hash(backpack,'bffcb4cd971a8eda');local s,why=S.read(api,game);assert(not s and why=='not_laser_backpack')
    hash(backpack,'af9b683ccb6ddc02')
end)
