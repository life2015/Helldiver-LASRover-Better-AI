local ffi=require('ffi')
local S=assert(loadfile(ROOT..'/src/snapshot.lua'))()
local blocks={}
local function alloc(n)
    local b=ffi.new('uint8_t[?]',n);blocks[#blocks+1]={b,n}
    return tonumber(ffi.cast('uintptr_t',b))
end
local function put(a,b)ffi.copy(ffi.cast('void *',a),b,#b)end
local function word(a,v)put(a,ffi.string(ffi.new('uint32_t[1]',v),4))end
local function ptr(a,v)put(a,ffi.string(ffi.new('uint64_t[1]',v),8))end
local function hash(a,s)put(a,(s:gsub('..',function(x)return string.char(tonumber(x,16))end)):reverse())end
local function entity(a,h,id,ref)
    hash(a,h);word(a+8,id);word(a+16,ref);word(a+20,1)
end
local function map(a,id,index)
    local data=alloc(64);ffi.fill(ffi.cast('void *',data),64,255)
    ptr(a,data);word(a+8,8);word(a+12,0xffffffff);word(a+16,1)
    word(data+(id%8)*8,id);word(data+(id%8)*8+4,index)
end
